"""Writes THIRD_PARTY_LICENSES.md: every library compiled into the desktop app (Rust crates linked into the Windows
binary, npm packages in the production interface) with its version, declared license and the license texts it ships.

Run from apps/desktop after `pnpm install` in ui/:  python scripts/notices.py   (--check: fail if the file is stale)
"""

import json
import re
import subprocess
import sys
from pathlib import Path

DESKTOP = Path(__file__).resolve().parent.parent
OUT = DESKTOP / "THIRD_PARTY_LICENSES.md"
LICENSE_FILE = re.compile(
    r"^(licen[cs]e|copying|notice|unlicense)([-._].*)?$", re.IGNORECASE
)


def run(cmd: list[str], cwd: Path) -> str:
    return subprocess.run(
        cmd,
        cwd=cwd,
        check=True,
        capture_output=True,
        encoding="utf-8",
        shell=sys.platform == "win32",
    ).stdout


def texts(folder: Path) -> list[str]:
    files = sorted(
        p for p in folder.iterdir() if p.is_file() and LICENSE_FILE.match(p.name)
    )
    return [
        # line ends trimmed, as the repository's whitespace hook would
        "\n".join(
            line.rstrip()
            for line in p.read_text(encoding="utf-8", errors="replace")
            .strip()
            .splitlines()
        )
        for p in files
    ]


def crates() -> list[tuple[str, str, str, Path]]:
    meta = json.loads(
        run(
            [
                "cargo",
                "metadata",
                "--format-version",
                "1",
                "--locked",
                "--filter-platform",
                "x86_64-pc-windows-msvc",
            ],
            DESKTOP,
        )
    )
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    # only normal dependencies end up in the binary; build scripts, proc macros and dev-dependencies do not
    seen, todo = set(), [m for m in members if pkgs[m]["name"] == "bayle-desktop"]
    while todo:
        for dep in nodes[todo.pop()]["deps"]:
            if (
                any(k["kind"] is None for k in dep["dep_kinds"])
                and dep["pkg"] not in seen
            ):
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    out = []
    for pid in seen - members:
        p = pkgs[pid]
        if any(t["kind"] == ["proc-macro"] for t in p["targets"]):
            continue
        out.append(
            (
                p["name"],
                p["version"],
                p.get("license") or p.get("license_file") or "unknown",
                Path(p["manifest_path"]).parent,
            )
        )
    return out


def npm() -> list[tuple[str, str, str, Path]]:
    listed = json.loads(
        run(["pnpm", "licenses", "list", "--prod", "--json"], DESKTOP / "ui")
    )
    return [
        (p["name"], v, lic, Path(path))
        for lic, ps in listed.items()
        for p in ps
        for v, path in zip(p["versions"], p["paths"])
    ]


def render(groups: dict[str, list[tuple[str, str, str, Path]]]) -> str:
    lines = [
        "# Third-party licenses (desktop app)",
        "",
        "Generated by `apps/desktop/scripts/notices.py` from `Cargo.lock` and `ui/pnpm-lock.yaml`; do not edit by",
        "hand. The engine's libraries and the other notices are in `THIRD_PARTY_NOTICES.md`.",
        "",
    ]
    by_text: dict[
        str, tuple[str, list[str]]
    ] = {}  # whitespace-folded text -> (text, packages)
    missing: list[str] = []
    for title, items in groups.items():
        items = sorted(set(items), key=lambda i: (i[0].lower(), i[1]))
        lines += [
            f"## {title} ({len(items)})",
            "",
            "| Package | Version | License |",
            "| --- | --- | --- |",
        ]
        for name, version, lic, folder in items:
            lines.append(f"| {name} | {version} | {lic} |")
            found = texts(folder)
            if not found:
                missing.append(f"{name} {version} ({lic})")
            for t in found:
                by_text.setdefault(" ".join(t.split()), (t, []))[1].append(
                    f"{name} {version}"
                )
        lines.append("")
    lines += [
        "## License texts",
        "",
        "Each text as the packages ship it, once, followed by the packages that ship it.",
        "",
    ]
    for t, users in sorted(by_text.values(), key=lambda tu: tu[1][0].lower()):
        lines += [f"**{', '.join(users)}**", "", "```text", t, "```", ""]
    if missing:
        lines += [
            "## Packages without a license file",
            "",
            "These declare their license in their manifest only. The standard texts of MIT and Apache-2.0 are in",
            "`THIRD_PARTY_NOTICES.md`; any other at `https://spdx.org/licenses/<id>.html`.",
            "",
            *(f"- {m}" for m in missing),
            "",
        ]
    return "\n".join(lines)


def main() -> int:
    text = render(
        {
            "Rust crates in the Windows binary": crates(),
            "npm packages in the interface": npm(),
        }
    )
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUT.name} is out of date: run python scripts/notices.py",
                file=sys.stderr,
            )
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
