"""Write apps/desktop/src/theme/tokens.css from src/bayle/ui/theme_tokens.py (itself generated from scripts/theme/tokens.json).

    python scripts/theme/gen_tokens.py [--check]

--check exits 1 when tokens.css is stale (a CI gate in the web job). Stdlib only.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[1] / "src" / "bayle" / "ui" / "theme_tokens.py"
OUT = HERE.parents[1] / "apps" / "desktop" / "src" / "theme" / "tokens.css"

spec = importlib.util.spec_from_file_location("theme_tokens", SRC)
assert spec and spec.loader
T = importlib.util.module_from_spec(spec)
sys.modules["theme_tokens"] = T
spec.loader.exec_module(T)


def kebab(name: str) -> str:
    return re.sub(r"([A-Z])", lambda m: "-" + m.group(1).lower(), name)


def css(v: str) -> str:
    """Qt writes translucent colours #AARRGGBB; CSS wants #RRGGBBAA."""
    return f"#{v[3:]}{v[1:3]}" if len(v) == 9 else v


def px(v: float) -> str:
    return f"{v:g}px"


def block(sel: str, roles: dict) -> str:
    body = "\n".join(f"  --{kebab(k)}: {css(v)};" for k, v in roles.items())
    return f"{sel} {{\n{body}\n}}\n"


def build() -> str:
    out = ["/* GENERATED by apps/desktop/src/theme/gen_tokens.py from src/bayle/ui/theme_tokens.py. Do not edit. */\n"]
    out.append(block(':root, :root[data-theme="dark"]', {**T.DARK}).replace("{", "{\n  color-scheme: dark;", 1))
    out.append(block(':root[data-theme="light"]', T.LIGHT).replace("{", "{\n  color-scheme: light;", 1))
    out.append(block(':root[data-theme="tarnished"]', T.TARNISHED).replace("{", "{\n  color-scheme: dark;", 1))
    # Tailwind utilities: colours follow the data-theme variables (inline = no copy at :root), the rest is static.
    th = ["@theme inline {"]
    th += [f"  --color-{kebab(k)}: var(--{kebab(k)});" for k in T.DARK]
    th += ["}", "", "@theme static {"]
    th += [f"  --radius-{kebab(k[6:]).lstrip('-')}: {px(v)};" for k, v in T.RADIUS.items()]
    th += [f"  --text-{kebab(k[4:]).lstrip('-')}: {px(v)};" for k, v in T.TYPE.items() if k.startswith("font")]
    th += [f"  --font-weight-{kebab(k[6:]).lstrip('-')}: {v};" for k, v in T.TYPE.items() if k.startswith("weight")]
    th += [
        f"  --duration-{kebab(k[1:]).lstrip('-')}: {v}ms;"
        for k, v in T.MOTION.items()
        if k.startswith("m") and isinstance(v, int) and k != "mTooltipDelay" and k != "mToastHold"
    ]
    th += [f"  --{kebab(k)}: {px(v)};" for k, v in T.GEOMETRY.items() if isinstance(v, int)]
    th += [
        f"  --font-ui: {', '.join(repr(f) if ' ' in f else f for f in dict.fromkeys(T.FONT_FAMILIES))};",
        f"  --font-head: '{T.FONT['fontHead']}', serif;",
        "}",
        "",
    ]
    out.append("\n".join(th))
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
